// ============================================================================
// Снимок состояния гонки для интерфейса.
//
// Зачем он существует. Интерфейс читал рабочее состояние пайплайна напрямую —
// общую карту машин, которую в это же время меняет поток приёма пакетов. Пока
// источник один и идёт вперёд, это сходило с рук. Как только появилась
// перемотка назад (состояние перестраивается прогоном записи), посыпались
// артефакты: машины прыгали, таймер и таблица показывали то новые позиции со
// старыми кругами, то данные, отставшие на шаг. Каждая заплатка закрывала
// одного потребителя из двенадцати, а следующий забытый возвращал баг.
//
// Граница проводится здесь. Пайплайн меняет своё рабочее состояние как хочет,
// а наружу отдаёт НЕИЗМЕНЯЕМЫЙ снимок — и только тогда, когда состояние
// согласовано целиком. Отсюда три следствия:
//   * увидеть половину перестройки невозможно ПО ПОСТРОЕНИЮ, а не по
//     внимательности разработчика панели;
//   * интерфейс читает снимок без блокировок и не соперничает с приёмом
//     пакетов за мьютекс — кадр перестаёт зависеть от плотности телеметрии;
//   * появляется то, чего раньше не было: сравнить два момента заезда, держать
//     вторую панель на том же состоянии, отдать снимок куда-то ещё.
//
// В снимок кладётся ЛЁГКОЕ представление машины. История телеметрических
// сэмплов (десять замеров в секунду на круг) сюда не входит: копировать её
// каждый кадр нельзя, а она дописываемая и читается отдельно.
// ============================================================================
namespace world
{
    /// Состояние одной машины на момент публикации.
    struct VehicleView
    {
        int32_t     id = 0;
        int32_t     device_id = 0;
        std::string name;
        glm::vec3   color{ 1.0f, 1.0f, 1.0f };

        // Положение и движение
        double x = 0.0;
        double y = 0.0;
        double heading = 0.0;
        double speed_kph = 0.0;
        double acceleration = 0.0;
        double g_force_x = 0.0;
        double g_force_y = 0.0;
        double track_progress = 0.0;
        double total_progress = 0.0;
        bool   apply_track_render_offset = true;

        // Гоночное состояние
        int   completed_laps = 0;
        int   current_lap_number = 0;
        int   best_lap_id = -1;
        float current_lap_timer = 0.0f;
        float best_lap_time = -1.0f;
        bool  has_started_first_lap = false;
        bool  is_leader = false;
        bool  is_finished = false;
        bool  is_lapped = false;
        bool  signal_lost = false;

        int16_t  fix_type = 0;
        uint32_t packet_utc_ms = 0;

        // Секторы ТЕКУЩЕГО круга: законченные — измеренным временем,
        // недоехавшие — SECTOR_TIME_NONE. Плюс сектор, в котором машина сейчас,
        // и сколько она в нём уже едет. Всё считается по меткам пакетов, а не
        // по кадрам, поэтому на одной и той же точке записи значения одни и те
        // же — см. SECTOR_COUNT в Vehicle.h.
        std::array<float, SECTOR_COUNT> sectors{
            SECTOR_TIME_NONE, SECTOR_TIME_NONE, SECTOR_TIME_NONE };
        int   current_sector = 0;
        float current_sector_elapsed = 0.0f;

        // Времена завершённых кругов — нужны таблицам и панелям.
        //
        // РАЗДЕЛЯЕМЫЙ указатель, а не копия. Снимок публикуется каждый кадр, и
        // копия здесь означала копию std::map с узлом на круг: сорок кругов на
        // двадцати машинах — восемьсот аллокаций на кадр ради времён, которые
        // не менялись с прошлого круга. Теперь карта пересобирается только
        // когда действительно изменилась, а снимки делят одну и ту же.
        //
        // Может быть пустым (машина без кругов) — читать через laps_ref().
        std::shared_ptr<const std::map<int, LapData>> laps;

        /// Круги машины. Всегда валидная ссылка: пустая карта, если кругов нет.
        const std::map<int, LapData>& laps_ref() const
        {
            static const std::map<int, LapData> empty;
            return laps ? *laps : empty;
        }
    };

    /// Согласованный срез мира. Неизменяем: опубликованный снимок никто не правит.
    struct Snapshot
    {
        std::map<int32_t, VehicleView> vehicles;
        std::vector<VehicleStanding>   standings;   // уже отсортированная таблица
        uint64_t                       revision = 0;
    };

    /// Публикует новый снимок. Зовёт RaceManager, когда состояние согласовано.
    void publish(std::shared_ptr<const Snapshot> snapshot);

    /// Текущий снимок. Никогда не nullptr, читается без блокировок.
    /// Держите возвращённый указатель на время работы с данными: пока он жив,
    /// содержимое не изменится, даже если пайплайн опубликует следующий.
    std::shared_ptr<const Snapshot> current();

    /// Удобный доступ к одной машине. nullptr, если её нет в снимке.
    const VehicleView* find(const Snapshot& snapshot, int32_t vehicle_id);
}
