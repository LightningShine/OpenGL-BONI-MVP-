#pragma once

#include <filesystem>

// ============================================================================
// Каталоги пользовательских данных.
//
// Всё, что приложение пишет по ходу работы, лежит под ОДНИМ корнем `saves` и
// разложено по смыслу:
//
//     saves/tracks    — карты трасс (.trk2, .txt)
//     saves/results   — протоколы заездов
//     saves/replays   — записи телеметрии (.rjl) для повторов
//     saves/logs      — журналы консоли
//
// Зачем понадобилось. Раньше эти четыре вида данных лежали в четырёх разных
// местах, причём в трёх из них вперемешку: трассы в `src/saves` (то есть
// внутри исходников), протоколы разом в `saves` и в `src/saves`, ещё часть в
// `race saves`, а записи повторов — в `logs` вместе с текстовыми журналами,
// потому что каталог задавался одной константой на двоих. Найти нужный файл
// через полгода было невозможно, и каждое новое место приходилось помнить
// наизусть.
//
// Здесь эти пути заданы ОДИН раз. Ни один модуль больше не пишет каталог
// строкой у себя: разъезжаться нечему.
//
// Пути относительные — как и раньше, они отсчитываются от рабочего каталога
// приложения. Это же свойство держит установленную копию работоспособной:
// данные лежат рядом с exe, в каталоге, куда пользователь имеет право писать
// (установка идёт per-user, см. installer.iss).
// ============================================================================
namespace app_paths
{
    const std::filesystem::path& root();       // saves
    const std::filesystem::path& tracks();     // saves/tracks
    const std::filesystem::path& results();    // saves/results
    const std::filesystem::path& replays();    // saves/replays
    const std::filesystem::path& logs();       // saves/logs

    /// Создаёт дерево каталогов и переносит данные из старой раскладки.
    /// Зовётся один раз при старте, ДО открытия журнала консоли: журнал уже
    /// должен писаться в новое место.
    void prepare();

    /// Открывает каталог в проводнике. Нужен пунктам меню «Open ... Folder»:
    /// оператор должен доставать записи и протоколы, не разыскивая, куда
    /// приложение их положило.
    /// Возвращает false, если открыть не удалось.
    bool open_in_explorer(const std::filesystem::path& directory);
}
