// ============================================================================
// ТИПЫ КРУГА: результат круга и телеметрическая история.
//
// Вынесены из Vehicle.h отдельно намеренно. Vehicle.h тянет за собой ввод,
// сетевой заголовок и конфигурацию — а результат круга нужен и тем, кто про
// машину ничего знать не должен (журнал записи в ReplayPlayer, панели). Через
// Vehicle.h такой заголовок затаскивал в чужой файл winsock и ломал сборку
// порядком включений.
// ============================================================================

// ============================================================================
// ТОЧКИ ХРОНОМЕТРАЖА
//
// Круг разбит на SECTOR_COUNT секторов точками замера. Точка 0 — линия
// старт/финиша, точки 1..N-1 — промежуточные, стоят на фиксированных долях
// круга. Одинаковые для всех машин и всех кругов.
//
// Так устроены все системы, которым верят: у MyLaps это физические петли в
// покрытии (каждый проезд над петлёй — запись «трекер + метка времени»), у
// MoTeC — split points по дистанции круга. Время сектора там ВСЕГДА разность
// двух меток пересечения, а не результат разбора накопленной истории.
//
// У нас было наоборот: секторы считались по логу телеметрических сэмплов —
// искали, между какими замерами прогресс перешёл через 1/3 и 2/3. Отсюда всё
// и ломалось. Лог пишется по кадрам, поэтому его плотность зависит от FPS и
// скорости воспроизведения; на повторе часть лога относится к ещё не сыгранной
// части записи; при неполном логе граница сектора не находится вовсе. Один
// сектор показывал 2.778, соседний — пусто, а круг при этом 46.190 — при том,
// что секторы обязаны давать в сумме круг.
//
// Теперь сектор — это интервал между двумя пересечениями, с метками из
// gps_utc_ms. Свойства получаются сами собой:
//   * сумма секторов равна кругу ПО ПОСТРОЕНИЮ — это разбиение одного отрезка;
//   * время не зависит ни от кадров, ни от скорости повтора, ни от того, каким
//     путём оператор пришёл в эту точку записи;
//   * законченный сектор неизменяем, поэтому «рекорд сектора» срабатывает один
//     раз, а не каждый кадр;
//   * живой заезд, повтор с ПК и запись с карты памяти трекера дают одни и те
//     же числа: считается всё из одного и того же потока пакетов.
// ============================================================================
inline constexpr int SECTOR_COUNT = 3;

// ============================================================================
// ЧАСТОТА ЗАМЕРА ТЕЛЕМЕТРИИ — ОДНО ЧИСЛО НА ВСЕХ.
//
// С этим шагом RaceManager кладёт LapInfo в историю круга, и это же число
// уходит в шапку выгрузки MoTeC (logging::export_motec_csv) как заявленная
// частота дискретизации. Пока константы стояли в двух файлах, правка шага в
// RaceManager молча делала шапку CSV враньём: анализатор считает по ней
// производные каналы и фильтрацию.
// ============================================================================
inline constexpr float  kTelemetrySampleInterval = 0.1f;                    // с
inline constexpr double kTelemetrySampleRateHz   = 1.0 / kTelemetrySampleInterval;

/// Время сектора не измерено. Ноль для этого не годится: он и сам по себе
/// осмысленное значение, и именно из-за него в журнал сыпались рекорды с
/// прочерком вместо времени.
inline constexpr float SECTOR_TIME_NONE = -1.0f;

/// Доля круга, на которой стоит точка замера `index` (0 — старт/финиш).
inline double sector_split_position(int index)
{
	return static_cast<double>(index) / static_cast<double>(SECTOR_COUNT);
}

struct LapData
{
	// Поля тут стоят дорого: LapData копируется в снимок мира каждый кадр, в
	// каждый ключевой кадр повтора, в журнал записи и в GetVehicleLapsCopy.
	// Именно поэтому здесь нет «места на будущее»: вектор telemetryPoints,
	// который никто никогда не заполнял, конструировался и разрушался в каждой
	// из этих копий. История замеров живёт в CarLapSessions::samples.
	float lapTime;                              // Lap time in seconds
	int positionAtFinish;                       // Position when crossing line

	// Времена секторов круга. SECTOR_TIME_NONE — сектор не был измерен (машина
	// заехала в середине круга, пропал сигнал). В сумме дают lapTime.
	std::array<float, SECTOR_COUNT> sectors;

	LapData() : lapTime(0.0f), positionAtFinish(0) { sectors.fill(SECTOR_TIME_NONE); }
	LapData(float time, int position) : lapTime(time), positionAtFinish(position)
	{
		sectors.fill(SECTOR_TIME_NONE);
	}
};

/// Одинаковы ли два результата круга. Нужно снимку мира: он публикует круги
/// РАЗДЕЛЯЕМЫМ указателем и пересобирает их, только когда они действительно
/// изменились (см. RaceManager::PublishSnapshot). Сравнение здесь дешевле любой
/// схемы с номером версии — и, в отличие от неё, не может отстать от кода,
/// который правит круги в очередном новом месте.
inline bool operator==(const LapData& a, const LapData& b)
{
	return a.lapTime == b.lapTime &&
	       a.positionAtFinish == b.positionAtFinish &&
	       a.sectors == b.sectors;
}
inline bool operator!=(const LapData& a, const LapData& b) { return !(a == b); }

struct LapInfo
{
	float timefromstart;
	double progress;
	std::chrono::steady_clock::time_point timestamp;
	double total_progress;
	float gForceX, gForceY;
	float aceleration, speed;
	int curentPosition;

	// Где машина была в этот момент — нормализованные координаты, тот же кадр,
	// что и m_normalized_x/y (без render offset: его накладывает тот, кто
	// рисует, ровно как для живой позиции). Без них история знает, КОГДА и
	// НАСКОЛЬКО быстро машина ехала, но не ГДЕ, и построить реальную линию
	// проезда не из чего — см. панель TRACK REPORT.
	double x = 0.0;
	double y = 0.0;

	// ГЕОГРАФИЯ ЗАМЕРА.
	//
	// Нормализованные x/y выше — это координаты В КАДРЕ ТРАССЫ: они годятся,
	// чтобы нарисовать линию проезда у себя, и ни для чего больше. Выгрузка в
	// сторонние анализаторы (VBOX/.vbo, см. logging::export_vbo) стоит на
	// широте с долготой, а курс и тип фикса определяют, можно ли этой точке
	// верить. Всё это есть в пакете, теряется только потому, что замер их не
	// сохранял.
	double  lat_dd = 0.0;       // широта, градусы (+ север)
	double  lon_dd = 0.0;       // долгота, градусы (+ восток)
	double  heading_deg = 0.0;  // курс, градусы 0..360 от севера по часовой
	int16_t fix_type = 0;       // тип решения GNSS: 0 — нет, 4 — RTK Fixed

	// Метка источника (gps_utc_ms, мс от полуночи UTC) того пакета, на котором
	// снят замер. Это АБСОЛЮТНЫЙ адрес момента: по нему запись находит свою
	// позицию напрямую, без арифметики со временем круга. Пока перемотка
	// считалась разницей «нужное время минус текущее», она промахивалась —
	// текущее время круга обновляется на кадр позже применённой перемотки, и
	// два щелчка подряд по одному месту уносили запись то вперёд, то назад.
	uint32_t utc_ms = 0;
};

struct CarLapSessions
{
	int lapnumber;
	int globalLapnumber;
	std::vector<LapInfo> samples;
};
