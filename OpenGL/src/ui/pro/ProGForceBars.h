#pragma once
#include "ProView.h"

// Перегрузка одной осью — столбиком от нуля.
//
// Круговая диаграмма (ProGForce) показывает обе оси сразу и хороша, чтобы
// увидеть форму заезда целиком. Но когда смотрят ОДНУ ось — сколько машина
// тормозит или сколько держит в повороте — точка в круге читается плохо:
// значение приходится оценивать глазом по двум координатам. Столбик отвечает на
// этот вопрос сразу, поэтому обе панели существуют отдельно и включаются по
// отдельности (боковое меню, группа DATA).
namespace Pro {
    // Продольная (разгон/торможение) — вертикальный столбик.
    void RenderGForceLongWindow(const ProContext& ctx, int32_t vehicleId, ImVec2 vpSz, float topH);

    // Поперечная (левый/правый поворот) — горизонтальный столбик.
    void RenderGForceLatWindow (const ProContext& ctx, int32_t vehicleId, ImVec2 vpSz, float topH);
}
