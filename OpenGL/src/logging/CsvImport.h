#pragma once

#include <array>
#include <cstdint>
#include <filesystem>
#include <string>
#include <vector>

// ============================================================================
// ЧТЕНИЕ ЧУЖОЙ ТЕЛЕМЕТРИИ ИЗ CSV
//
// Зачем таблица, а не «формат RaceBox», «формат RaceChrono» и так далее.
// Логгеры разные, а отдают все одно и то же: строку на замер, колонку на
// величину. Разбирать каждый по отдельности значит писать по парсеру на
// устройство и дописывать новый при каждой покупке. Вместо этого читаем
// ЛЮБУЮ таблицу и один раз спрашиваем оператора, какая колонка что означает.
// Одним окном закрываются RaceChrono, TrackAddict, RaceBox, VBOX CSV, наш
// собственный экспорт и всё, что вообще умеет сохранять таблицу.
//
// КУДА ЭТО ПОПАДАЕТ. Импорт не заводит второй проигрыватель и не трогает
// хронометраж: он переводит таблицу в НАШИ ПАКЕТЫ и пишет обычную запись
// .rjl. Дальше файл открывается тем же replay_open, что и запись с приёмника,
// и круги, секторы, карта и графики считаются существующим кодом. Второй
// реализации подсчёта не появляется — а значит, и второго набора багов.
//
// ЧЕГО ЖДАТЬ ОТ ЧУЖИХ ДАННЫХ. Точность у них своя: у нас RTK — сантиметры, у
// телефона или бытового логгера — метры. Времена кругов и секторов выйдут
// заметно шумнее наших. Это свойство источника, а не импорта.
// ============================================================================
namespace logging
{
    /// Разобранная таблица: имена колонок и НАЧАЛО строк значений как есть, без
    /// приведения к числам. Приводим позже и только те колонки, которые
    /// оператор к чему-то привязал.
    ///
    /// ФАЙЛ ЦЕЛИКОМ ЗДЕСЬ НЕ ЛЕЖИТ. Раньше лежал: часовой лог на 25 Гц — это
    /// 90 000 строк по 18 ячеек, полтора миллиона std::string в памяти ради
    /// окна, которому нужны имена колонок и десяток строк на пробу. Теперь
    /// таблица держит только голову файла, а конвертация читает файл вторым
    /// проходом (см. convert_csv_to_replay).
    struct CsvTable
    {
        std::filesystem::path                 source;
        std::vector<std::string>              columns;
        /// Первые PREVIEW_ROWS строк данных — на определение формата времени и
        /// на показ в окне привязки. НЕ весь файл.
        std::vector<std::vector<std::string>> rows;
        /// Номер строки файла, с которой начинаются данные (шапка и подписи
        /// единиц выше). По нему второй проход находит своё место.
        size_t                                first_data_line = 0;
        /// Сколько строк данных в файле всего. Именно это число видит оператор.
        size_t                                data_rows = 0;
        char                                  delimiter = ',';
        /// В файле десятичная ЗАПЯТАЯ. Идёт в паре с разделителем: там, где
        /// колонки разделены точкой с запятой или табом, дроби почти всегда
        /// пишут через запятую — это одна и та же региональная настройка.
        bool                                  comma_decimal = false;

        bool empty() const { return data_rows == 0 || columns.empty(); }
    };

    /// Как в файле записано время. Определяется по виду значений, но оператор
    /// может поправить: ошибиться здесь — значит получить заезд длиной в сутки
    /// или в одну секунду, и никакая другая колонка об этом не скажет.
    enum class CsvTimeFormat
    {
        SecondsFromStart,  // 0.000, 0.040, 0.080 …
        TimeOfDay,         // 14:20:39.100
        UtcHhmmss,         // 142039.10 — так время пишет VBO
        UnixSeconds,
        UnixMillis,
    };

    /// В каких единицах лежит скорость. Из имени колонки видно не всегда,
    /// а разница между км/ч и м/с — это множитель 3.6 во всех графиках.
    enum class CsvSpeedUnit { Kph, Mps, Mph };

    /// Величины, которые импорт умеет забирать из таблицы.
    ///
    /// Обязательны только время и координаты: из них выводится всё остальное
    /// (см. convert_csv_to_replay). Привязанная колонка всегда важнее
    /// вычисленной — измеренному значению верим больше, чем производной.
    enum class CsvChannel
    {
        Time = 0,
        Latitude,
        Longitude,
        Speed,
        Acceleration,
        GForceLong,
        GForceLat,
        FixType,
        Count
    };

    struct CsvMapping
    {
        /// Индекс колонки для каждой величины; -1 — не привязана.
        std::array<int, static_cast<size_t>(CsvChannel::Count)> column;

        CsvTimeFormat time_format = CsvTimeFormat::SecondsFromStart;
        CsvSpeedUnit  speed_unit  = CsvSpeedUnit::Kph;
        int32_t       vehicle_id  = 1;

        CsvMapping() { column.fill(-1); }

        int  of(CsvChannel channel) const { return column[static_cast<size_t>(channel)]; }
        void set(CsvChannel channel, int index) { column[static_cast<size_t>(channel)] = index; }
    };

    /// Подпись величины для окна привязки.
    const char* csv_channel_label(CsvChannel channel);

    /// Без этой величины импорт невозможен (время и координаты).
    bool csv_channel_required(CsvChannel channel);

    /// Пояснение, откуда возьмётся величина, если колонку не привязать.
    const char* csv_channel_hint(CsvChannel channel);

    /// Читает таблицу. Разделитель (`,` `;` таб) и строку с именами колонок
    /// находит сам: у логгеров перед таблицей обычно лежит шапка с настройками
    /// прибора, а под именами колонок — строка единиц.
    ///
    /// Возвращает false и оставляет причину в `error`.
    bool read_csv(const std::filesystem::path& path, CsvTable& table, std::string* error);

    /// Догадка о привязке по именам колонок и по виду значений.
    CsvMapping guess_mapping(const CsvTable& table);

    /// Переводит таблицу в запись .rjl в каталоге `directory`.
    ///
    /// Скорость, ускорение и перегрузки, если колонки для них не привязаны,
    /// ВЫЧИСЛЯЮТСЯ из координат и времени. Это не выдумка: ровно так их
    /// получает любой анализатор GPS-данных, включая сам VBOX, когда в приборе
    /// нет отдельного датчика. Поперечная перегрузка при этом считается только
    /// на ходу — на стоящей машине курс не определён и число вышло бы из шума.
    ///
    /// Путь созданного файла — в `out_path`. Возвращает false и оставляет
    /// причину в `error`.
    bool convert_csv_to_replay(const CsvTable& table, const CsvMapping& mapping,
                               const std::filesystem::path& directory,
                               std::filesystem::path& out_path, std::string* error);
}
