#pragma once

// Только типы круга: писателю нужен ЗАМЕР, а не машина. Vehicle.h тянет ввод и
// сетевой заголовок, а вместе с ними winsock — в чужой единице трансляции это
// ломает сборку порядком включений.
#include "vehicle/LapTypes.h"

#include <cstdint>
#include <filesystem>
#include <map>
#include <string>
#include <vector>

// ============================================================================
// ВЫГРУЗКА ЗАЕЗДА В ОТКРЫТЫЕ ФОРМАТЫ
//
// Два формата, потому что анализаторы делятся ровно надвое.
//
//   .vbo  (RaceLogic VBOX) — простой текст; проверено на Circuit Tools, там
//         открывается как есть. Де-факто обменный формат для GPS-телеметрии:
//         наши данные — координаты плюс перегрузки — ложатся в него один в
//         один, потому что VBOX пишет ровно это.
//
//   .csv  в раскладке MoTeC — таблица, которую читает что угодно: Excel,
//         pandas, MATLAB. Раскладка MoTeC выбрана потому, что она сама по себе
//         обычный CSV и ничего не отнимает у остальных, а импорт i2 (только
//         Pro) при этом получает файл в ожидаемом виде.
//
// AiM Race Studio НИ ТОГО, НИ ДРУГОГО НЕ ЧИТАЕТ — в его списке импорта только
// собственные .xrk/.xrz/.drk, видеофайлы и телеметрия симуляторов. Отдельного
// формата под него здесь нет и, пока не появится описание .tqm или .drk, быть
// не может.
//
// Оба пишутся из ОДНОЙ таблицы каналов (см. TelemetryExport.cpp). Это главное
// в устройстве модуля: два независимых списка каналов разошлись бы на первой
// же правке, и один и тот же заезд в двух форматах перестал бы совпадать.
//
// Модуль — ЧИСТЫЙ ПИСАТЕЛЬ. Он не знает ни про повтор, ни про живой заезд, ни
// про то, какая машина сейчас выбрана: ему дают готовые замеры по кругам и
// подписи для шапки. Поэтому одна и та же выгрузка работает и с журналом
// записи, и с историей живой машины.
// ============================================================================
namespace logging
{
    /// Подписи для шапки файла. Пустые поля просто не печатаются.
    struct ExportMeta
    {
        std::string venue;              // трасса
        std::string vehicle;            // машина/номер
        std::string driver;             // пилот
        uint32_t    date_yyyymmdd = 0;  // день заезда; 0 — взять сегодняшний
    };

    /// Круг → его замеры по порядку проезда. Ровно то, что лежит в журнале
    /// записи (telemetry::VehicleJournal::lap_samples) и в истории живой
    /// машины (Vehicle::laps).
    using ExportSamples = std::map<int, std::vector<LapInfo>>;

    /// Пишет замеры в файл .vbo (RaceLogic VBOX).
    ///
    /// ЧТО ЗНАТЬ ПРО ФОРМАТ (иначе трасса уедет в другое полушарие):
    ///   * широта и долгота пишутся в МИНУТАХ, а не в градусах;
    ///   * у долготы в VBOX положительным считается ЗАПАД;
    ///   * время — UTC в виде HHMMSS.SS;
    ///   * первые восемь каналов обязательны и идут строго в своём порядке.
    ///
    /// Замеры без координат (нет фикса — широта и долгота нулевые) в файл не
    /// идут: строка без позиции для анализатора мусор, а не «пропуск».
    ///
    /// Возвращает false и оставляет причину в `error` (если он передан).
    /// Отсутствие пригодных замеров — тоже отказ: молча записанный пустой файл
    /// неотличим от сломанной выгрузки.
    bool export_vbo(const std::filesystem::path& path,
                    const ExportMeta& meta,
                    const ExportSamples& lap_samples,
                    std::string* error = nullptr);

    /// Пишет замеры в .csv в раскладке MoTeC: шапка из пар «ключ, значение»,
    /// строка имён каналов, строка единиц, дальше данные.
    ///
    /// Время здесь — СЕКУНДЫ ОТ НАЧАЛА ВЫГРУЗКИ, а координаты — обычные
    /// градусы с положительным востоком: i2 ждёт именно этого, и соглашения
    /// VBOX сюда переносить нельзя.
    ///
    /// Отказы — как у export_vbo.
    bool export_motec_csv(const std::filesystem::path& path,
                          const ExportMeta& meta,
                          const ExportSamples& lap_samples,
                          std::string* error = nullptr);
}
