#pragma once

#include <cstdint>
#include <filesystem>
#include <string>

// ============================================================================
// Воспроизведение записи `.rjl` (этап 3).
//
// Проигрыватель отдаёт записанные пакеты в telemetry::ingest_wire_packet() —
// в ту же точку, куда их отдаёт приёмник. Поэтому повтор проходит весь тракт
// целиком: CRC, пайплайн машин, детекция пересечений старт/финиша,
// хронометраж. Второй реализации подсчёта не появляется, и это главное:
// времена кругов в повторе обязаны совпасть с живым заездом.
//
// Совпадают они потому, что этап 2 привязал хронометраж к меткам пакетов
// (gps_utc_ms), а не к кадрам. Скорость воспроизведения меняет только то,
// КОГДА пакет попадёт в тракт, но не то, что в нём написано.
//
// Перемотка назад делается пересчётом: состояние гонки сбрасывается и запись
// прогоняется с начала до нужной точки на максимальной скорости. Это дёшево
// после того, как проекция на трек перестала копировать трек на каждый пакет.
// ============================================================================
namespace telemetry
{
    struct ReplayStatus
    {
        bool        active = false;
        bool        paused = false;
        double      speed = 1.0;
        size_t      position = 0;      // индекс текущей записи
        size_t      total = 0;
        uint32_t    position_ms = 0;   // от начала записи
        uint32_t    duration_ms = 0;
        std::string file_name;
    };

    /// Открывает запись и начинает воспроизведение с паузы.
    /// Требует загруженного трека: без геометрии и origin позиции не
    /// восстановить. Не запускается, если активен живой источник — иначе два
    /// потока пакетов смешались бы в одном пайплайне.
    bool replay_open(const std::filesystem::path& path);

    void replay_close();
    bool replay_is_active();

    void replay_toggle_pause();
    void replay_set_speed(double speed);

    /// Шаг на `ticks` тиков записи (может быть отрицательным).
    /// Тик — один период выборки телеметрии, см. REPLAY_TICK_MS.
    void replay_step(int ticks);

    /// Смещение на `seconds` секунд записи — для непрерывной перемотки
    /// удержанием клавиши.
    void replay_scrub(double seconds);

    ReplayStatus replay_status();

    /// Период выборки телеметрии: один «тик» перемотки.
    inline constexpr uint32_t REPLAY_TICK_MS = 20;
}
