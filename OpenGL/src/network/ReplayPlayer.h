#pragma once

#include <cstdint>
#include <filesystem>
#include <functional>
#include <string>

// ============================================================================
// Воспроизведение записи `.rjl` (этап 3).
//
// Проигрыватель отдаёт записанные пакеты в telemetry::ingest_wire_packet() —
// в ту же точку, куда их отдаёт приёмник. Поэтому повтор проходит весь тракт
// целиком: CRC, пайплайн машин, детекция пересечений старт/финиша,
// хронометраж. Второй реализации подсчёта не появляется, и это главное:
// времена кругов в повторе обязаны совпасть с живым заездом.
//
// Совпадают они потому, что этап 2 привязал хронометраж к меткам пакетов
// (gps_utc_ms), а не к кадрам. Скорость воспроизведения меняет только то,
// КОГДА пакет попадёт в тракт, но не то, что в нём написано.
//
// Перемотка назад делается пересчётом: состояние гонки сбрасывается и запись
// прогоняется с начала до нужной точки на максимальной скорости. Это дёшево
// после того, как проекция на трек перестала копировать трек на каждый пакет.
// ============================================================================
namespace telemetry
{
    struct ReplayStatus
    {
        bool        active = false;
        bool        paused = false;
        double      speed = 1.0;
        size_t      position = 0;      // индекс текущей записи
        size_t      total = 0;
        uint32_t    position_ms = 0;   // от начала записи
        uint32_t    duration_ms = 0;
        std::string file_name;
        std::string track_name;        // трасса записи; пусто, если не указана
        uint32_t    date_yyyymmdd = 0; // день заезда из заголовка; 0 = не записан
    };

    /// Как приложение загружает трассу. Задаётся один раз при старте.
    ///
    /// Нужно, чтобы запись со встроенной трассой открывалась сама: модуль
    /// повтора знает, ЧТО надо загрузить, но не должен знать, как устроена
    /// загрузка и отрисовка. Обратная зависимость (повтор → UI) сделала бы
    /// невозможным ни то, ни другое менять отдельно.
    void replay_set_track_loader(std::function<bool(const std::filesystem::path&)> loader);

    /// Открывает запись и начинает воспроизведение с паузы.
    ///
    /// Трассу берёт на себя: несёт запись свою — загружает её, названа она в
    /// заголовке — ищет по имени в каталоге трасс. Загруженная заранее трасса
    /// нужна только записям, которые о своей трассе не говорят ничего.
    /// Не запускается, если активен живой источник — иначе два потока пакетов
    /// смешались бы в одном пайплайне.
    ///
    /// При отказе причина остаётся в replay_last_error() — её показывает
    /// пользователю UI. Возврат false без причины считается ошибкой: молча
    /// отказавшая кнопка неотличима от сломанной.
    bool replay_open(const std::filesystem::path& path);

    /// Почему не открылась последняя запись. Пусто, если последняя попытка
    /// удалась. Текст готов к показу: он же уходит в консоль.
    std::string replay_last_error();

    void replay_close();
    bool replay_is_active();

    void replay_toggle_pause();

    /// Лёгкая проверка паузы — зовётся каждый кадр, поэтому без снимка статуса.
    bool replay_is_paused();

    /// Пакеты сейчас подаёт САМ проигрыватель (в этом потоке).
    ///
    /// По этому признаку тракт приёма отличает записанный заезд от всего, что
    /// приходит со стороны, пока повтор открыт: подключённого на ходу приёмника,
    /// машины, выехавшей на трассу прямо сейчас, потока с сервера. Их машины не
    /// должны появляться среди участников записи — на экране они неотличимы.
    bool replay_is_feeding();

    /// Идёт пересчёт после перемотки назад. Пока он идёт, состояние гонки
    /// неполное: скормлена лишь часть записи. Читать из него результаты нельзя —
    /// именно так в таблице мелькал чужой лидер.
    bool replay_is_rebuilding();
    void replay_set_speed(double speed);

    /// Шаг на `ticks` тиков записи (может быть отрицательным).
    /// Тик — один период выборки телеметрии, см. REPLAY_TICK_MS.
    void replay_step(int ticks);

    /// Смещение на `seconds` секунд записи — для непрерывной перемотки
    /// удержанием клавиши. Только копит сдвиг; исполняет его
    /// replay_apply_pending_seek().
    void replay_scrub(double seconds);

    /// Номер отката назад: растёт на каждом откате. По нему потребители, которые
    /// НАКАПЛИВАЮТ производную от хода заезда историю, узнают, что накопленное
    /// относится к ещё не проигранной части записи. Пример — журнал событий PRO:
    /// лучшие круги и секторы в нём выведены по ходу заезда, и после отката
    /// назад его надо начинать заново, иначе он отчитывается о событиях из
    /// будущего.
    uint64_t replay_rewind_revision();

    /// Исполняет накопленную перемотку. Зовётся РАЗ В КАДР из главного цикла,
    /// сразу после разбора ввода и до отрисовки.
    ///
    /// Почему в кадре, а не в потоке проигрывателя. Перемотка вперёд всегда
    /// показывалась через Update главного цикла — один шаг на кадр, в такт
    /// отрисовке. Назад же шаги исполнялись потоком проигрывателя по своему
    /// таймеру: на 60 кадрах в секунду это давало то два шага на кадр, то ни
    /// одного, и вдобавок откат держал мьютекс машин, на котором главный поток
    /// вставал. Кадр удлинялся → следующий запрошенный сдвиг рос → откат
    /// удлинялся: рывки сами себя разгоняли. Теперь обе стороны — один шаг на
    /// кадр в том же потоке, что и рисует.
    void replay_apply_pending_seek();

    ReplayStatus replay_status();

    /// Период выборки телеметрии: один «тик» перемотки.
    inline constexpr uint32_t REPLAY_TICK_MS = 20;
}
