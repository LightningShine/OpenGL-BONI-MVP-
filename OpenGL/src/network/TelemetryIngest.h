#pragma once

#include "../logging/TelemetryLog.h"
#include "../network/Server.h"

#include <cstdint>

// ============================================================================
// Единственная точка входа проводного пакета телеметрии.
//
// «Проводной» — значит 37 байт формата rajagp::RajaTelemetryPacket, ровно как
// их шлёт трекер. Через эту точку обязаны заходить ВСЕ источники: читатель
// COM-порта, синтетический генератор и будущий проигрыватель `.rjl`. Если
// источник пойдёт мимо, живой поток и воспроизведённый начнут расходиться —
// а на этом расхождении держится вся система повторов.
//
// Здесь и только здесь происходит: проверка CRC, запись сырых байт в журнал,
// запоминание последнего пакета и подача в пайплайн машин.
// ============================================================================
namespace telemetry
{
    /// Включает приём и открывает журнал записи в app_paths::replays().
    /// Повторный вызов при уже активном приёме игнорируется — источник в
    /// приложении один. Возвращает false, если приём уже был запущен.
    bool ingest_start(logging::TelemetryLogSource source);

    /// Останавливает приём и закрывает журнал (с самопроверкой файла).
    void ingest_stop();

    /// Принимает один проводной пакет: `payload_after_magic` — ровно
    /// rajagp::kRajaPayloadAfterMagic байт, идущих за маркером 'RAJA'.
    /// Возвращает false, если CRC не сошёлся: такой пакет не пишется в журнал
    /// и не попадает в пайплайн.
    /// `out_packet` (если задан) получает разобранный пакет — читателю порта он
    /// нужен для диагностики, чтобы не разбирать те же байты второй раз.
    bool ingest_wire_packet(const uint8_t* payload_after_magic,
                            TelemetryPacket* out_packet = nullptr);

    /// Копия последнего успешно принятого пакета. false, если приёма ещё не было.
    /// Используется калибровкой origin по линии старт/финиша.
    bool last_received_packet(TelemetryPacket& out_packet);
}
