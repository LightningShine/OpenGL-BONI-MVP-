#include <cstdint>
#include <vector>

// ============================================================================
// Синтетический источник проводной телеметрии.
//
// Гоняет виртуальные машины по загруженному треку и отдаёт НАСТОЯЩИЕ 37-байтные
// пакеты rajagp::RajaTelemetryPacket (с CRC) в ту же точку приёма, куда их
// отдаёт читатель COM-порта. То есть проходит весь тракт целиком, включая
// запись в `.rjl` — в отличие от симуляции по клавише T, которая пишет позиции
// прямо в g_vehicles и мимо телеметрии.
//
// Зачем: хронометраж нельзя проверить на живом заезде, потому что заезд
// невоспроизводим. Здесь же поток пакетов детерминирован — при одном и том же
// сценарии и семени ГСЧ байты на выходе совпадают до последнего, независимо от
// частоты кадров и загрузки машины. На таком входе видно, что подсчёт кругов
// даёт один и тот же ответ, а не «примерно тот же».
//
// Отдельно задаются патологии, из-за которых ломается реальная телеметрия:
// потери пакетов, джиттер меток, пропажа связи, деградация фикса с боковым
// сносом позиции и переход времени через полночь.
// ============================================================================
namespace telemetry
{
    struct SyntheticScenario
    {
        // --- поток ---
        int      car_count = 5;
        uint32_t sample_interval_ms = 20;   // 20 мс = 50 Гц на машину
        uint32_t duration_seconds = 300;
        uint32_t seed = 1;                  // фиксирует все случайные решения

        // --- движение ---
        double base_speed_kph = 45.0;
        double speed_spread_kph = 25.0;     // разброс между машинами

        // --- скорость проигрывания ---
        // 1.0 = реальное время, 10.0 = в десять раз быстрее, 0.0 = без пауз
        // (нужно, чтобы прогнать получасовую гонку за секунды). На содержимое
        // пакетов не влияет: метки времени синтетические.
        double speed_multiplier = 1.0;

        // --- патологии ---
        int      packet_loss_percent = 0;     // равномерные потери радиоканала
        uint32_t jitter_ms = 0;               // разброс метки времени, ±
        int      gap_car_index = -1;          // у какой машины пропадёт связь (-1 = ни у какой)
        uint32_t gap_start_second = 0;
        uint32_t gap_duration_seconds = 0;
        bool     degrade_fix_after_gap = false;  // вернуться с fix_type = 1
        double   position_bias_meters = 0.0;     // боковой снос позиции при плохом фиксе
        bool     wrap_midnight = false;          // начать за несколько секунд до полуночи
    };

    /// Строит ВЕСЬ поток сценария заранее и возвращает его как непрерывную
    /// последовательность 37-байтных проводных пакетов.
    ///
    /// Чистая функция: результат зависит только от аргументов. Ни системные
    /// часы, ни частота кадров, ни загрузка машины на него не влияют — поэтому
    /// два вызова с одним сценарием дают побайтово одинаковый результат, и на
    /// нём можно доказывать, что хронометраж воспроизводим.
    std::vector<uint8_t> build_synthetic_stream(const SyntheticScenario& scenario,
                                                const std::vector<SplinePoint>& track,
                                                const MapOrigin& origin,
                                                const glm::vec2& render_offset);

    /// Запускает поток генерации. Требует загруженного трека и валидного origin.
    /// Возвращает false, если условия не выполнены или генератор уже работает.
    bool synthetic_start(const SyntheticScenario& scenario);

    /// Останавливает генерацию и дожидается завершения потока.
    void synthetic_stop();

    bool synthetic_is_running();
}
