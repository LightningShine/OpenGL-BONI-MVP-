#pragma once

#include <algorithm>
#include <cstdint>

// ============================================================================
// Арифметика времени хронометража.
//
// Метка каждого пакета — gps_utc_ms, миллисекунды от полуночи UTC. Она общая
// для всех трекеров (приходит из GNSS) и не зависит ни от частоты кадров, ни
// от скорости воспроизведения записи — именно поэтому время круга считается на
// ней, а не на длительностях кадров рендера.
//
// Плата за это — переполнение в полночь: 86 400 000 мс, и счётчик обнуляется.
// Все интервалы считаются только через функции ниже, напрямую вычитать метки
// нельзя. Вынесено в заголовок, чтобы арифметику можно было проверить тестом и
// чтобы проигрыватель записей потом считал круги ровно так же.
// ============================================================================
namespace racing
{
    inline constexpr uint32_t MS_PER_DAY = 86'400'000u;

    /// Интервал от `from` до `to` с учётом перехода через полночь.
    /// Предполагается, что интервал меньше суток.
    inline uint32_t utc_elapsed_ms(uint32_t from, uint32_t to)
    {
        return (to >= from) ? (to - from) : (MS_PER_DAY - from + to);
    }

    /// Момент внутри отрезка [from, to] на доле `fraction` его длины.
    /// Долю даёт геометрия пересечения (где именно на отрезке легла линия),
    /// а не время кадра — отсюда точность в миллисекунды при любом FPS.
    inline uint32_t utc_at_fraction(uint32_t from, uint32_t to, float fraction)
    {
        const uint32_t span = utc_elapsed_ms(from, to);
        // Округляем к ближайшей миллисекунде, а не усекаем: усечение смещало бы
        // каждый момент пересечения вниз, и на круге ошибка складывалась бы
        // дважды — на его начале и на конце.
        const uint32_t offset =
            static_cast<uint32_t>(span * std::clamp(fraction, 0.0f, 1.0f) + 0.5f);
        return (from + offset) % MS_PER_DAY;
    }
}
